-- Those pointed at specific rows in the original database and would break a
-- fresh project. The app always sends "group" on insert.
-- BettingOption is added to supabase_realtime (the app subscribes to it).

create table public."Users" (
  id uuid primary key references auth.users (id) on update cascade on delete cascade,
  username text not null unique,
  is_banned boolean not null default false,
  bio text not null default '' constraint "Users_bio_length" check (length(bio) <= 300),
  has_seen_onboarding boolean not null default false
);

create table public."Group" (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  description text not null,
  created_by uuid not null references public."Users" (id) on update cascade on delete cascade,
  is_publicly_joinable boolean not null default false
);

create table public."UsersGroupMembership" (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "user" uuid not null references public."Users" (id) on update cascade on delete cascade,
  "group" bigint not null references public."Group" (id) on update cascade on delete cascade,
  constraint unique_user_group unique ("user", "group")
);

create table public."RequestJoinGroup" (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "user" uuid not null references public."Users" (id) on update cascade on delete cascade,
  "group" bigint not null references public."Group" (id) on update cascade on delete cascade,
  message text not null
);

create table public."BettingGame" (
  id bigint generated by default as identity primary key,
  title text not null,
  created_at timestamptz not null default now(),
  deadline timestamptz not null,
  referee uuid not null references public."Users" (id),
  decided_at timestamptz,
  created_by uuid not null references public."Users" (id) on update cascade on delete restrict,
  "group" bigint not null references public."Group" (id) on update cascade on delete cascade
);

create table public."BettingOption" (
  id bigint generated by default as identity primary key,
  title text not null,
  game bigint not null references public."BettingGame" (id) on update cascade on delete cascade,
  is_winning boolean
);

create table public."Bets" (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  game bigint not null references public."BettingGame" (id) on update cascade on delete cascade,
  option bigint not null references public."BettingOption" (id) on update cascade on delete cascade,
  "user" uuid not null references public."Users" (id) on update cascade on delete cascade,
  amount bigint not null,
  multiplier double precision not null
);

create table public."UsersExcludedFrom" (
  id bigint generated by default as identity primary key,
  "user" uuid not null references public."Users" (id) on update cascade on delete cascade,
  game bigint not null references public."BettingGame" (id) on update cascade on delete cascade
);

create table public."PointsHistory" (
  id bigint generated by default as identity primary key,
  "user" uuid not null references public."Users" (id) on update cascade on delete cascade,
  amount bigint not null default 200,
  "timestamp" timestamptz default now(),
  "group" bigint not null references public."Group" (id) on update cascade on delete cascade
);

create table public."DecisionNotification" (
  id bigint generated by default as identity primary key,
  "user" uuid not null references public."Users" (id) on update cascade on delete cascade,
  game bigint not null references public."BettingGame" (id) on update cascade on delete cascade
);

